/**
 * Lookup price trend for any lot name or material name
 */
export function getMaterialPriceTrend(materialIdOrName: string, fallbackRate: number = 400): MaterialPriceTrend {
  // Try direct ID lookup
  if (MATERIAL_PRICE_TRENDS_MAP[materialIdOrName]) {
    return MATERIAL_PRICE_TRENDS_MAP[materialIdOrName];
  }

  // Try matching by material name keywords
  const lower = materialIdOrName.toLowerCase();
  if (lower.includes('pcb') || lower.includes('motherboard') || lower.includes('server') || lower.includes('circuit')) {
    return MATERIAL_PRICE_TRENDS_MAP.mat_pcb_high;
  }
  if (lower.includes('copper') || lower.includes('wire') || lower.includes('cable') || lower.includes('winding')) {
    return MATERIAL_PRICE_TRENDS_MAP.mat_copper_wire;
  }
  if (lower.includes('battery') || lower.includes('lithium') || lower.includes('li-ion') || lower.includes('cell')) {
    return MATERIAL_PRICE_TRENDS_MAP.mat_li_battery;
  }
  if (lower.includes('magnet') || lower.includes('neodymium') || lower.includes('hdd') || lower.includes('motor')) {
    return MATERIAL_PRICE_TRENDS_MAP.mat_neodymium_hdds;
  }
  if (lower.includes('crt') || lower.includes('tube') || lower.includes('glass') || lower.includes('funnel')) {
    return MATERIAL_PRICE_TRENDS_MAP.mat_crt_glass;
  }
  if (lower.includes('plastic') || lower.includes('casing') || lower.includes('polymer') || lower.includes('abs')) {
    return MATERIAL_PRICE_TRENDS_MAP.mat_flame_plastics;
  }

  // Generate dynamic trend for custom unlisted lots
  const dynRate = fallbackRate > 0 ? fallbackRate : 450;
  return {
    materialId: `dynamic_${Date.now()}`,
    materialName: materialIdOrName,
    materialName_hi: materialIdOrName,
    category: 'custom',
    currentRate: dynRate,
    cpcbFloorRate: Math.round(dynRate * 0.9),
    trend30dPct: 3.2,
    high30d: Math.round(dynRate * 1.06),
    low30d: Math.round(dynRate * 0.94),
    volatilityIndex: 3.8,
    forecastNextMonth: 'Evaluating under CPCB Schedule III Mandi Benchmark',
    forecastChangePct: 2.5,
    crmComposition: {
      copperPct: 12.0,
      lithiumPct: 1.5,
      cobaltPct: 2.0,
      neodymiumPct: 1.0,
      goldGramsPerTon: 80
    },
    history7d: generatePriceSeries(dynRate, 10, 1.5, 7),
    history30d: generatePriceSeries(dynRate, 20, 3.2, 30),
    history90d: generatePriceSeries(dynRate, 35, 6.5, 90),
    history1y: generatePriceSeries(dynRate, 50, 12.0, 365)
  };
}
