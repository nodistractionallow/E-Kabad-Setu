// Helper to generate simulated price points
const generatePriceSeries = (
  baseRate: number,
  volatility: number,
  trendPct: number,
  daysCount: number,
  startDateStr: string = '2026-09-04'
): LotPricePoint[] => {
  const points: LotPricePoint[] = [];
  const baseDate = new Date(startDateStr);
  
  for (let i = daysCount - 1; i >= 0; i--) {
    const d = new Date(baseDate);
    d.setDate(d.getDate() - i);
    const dateFormatted = d.toISOString().split('T')[0];
    
    // Progressive drift with slight sine wave and random noise
    const progressRatio = (daysCount - i) / daysCount;
    const drift = (trendPct / 100) * baseRate * progressRatio;
    const wave = Math.sin(i * 0.45) * (volatility * 0.6);
    const noise = (Math.random() - 0.5) * (volatility * 0.8);
    
    const spot = Math.round(baseRate - (trendPct / 100) * baseRate + drift + wave + noise);
    const cpcbFloor = Math.round(baseRate * 0.92 + (drift * 0.5));
    const lmeEquiv = Math.round(spot * 1.08 + Math.cos(i * 0.3) * (volatility * 0.5));
    const high = Math.round(spot * 1.03);
    const low = Math.round(spot * 0.97);
    const volume = Math.round(150 + Math.random() * 450 + (daysCount > 30 ? 300 : 0));
    
    const prevSpot = points.length > 0 ? points[points.length - 1].marketSpotRate : spot;
    const changePct = Number(((spot - prevSpot) / (prevSpot || 1) * 100).toFixed(2));

    points.push({
      date: dateFormatted,
      cpcbRate: cpcbFloor,
      marketSpotRate: spot,
      lmeEquivRate: lmeEquiv,
      volumeKg: volume,
      high: high,
      low: low,
      changePct: changePct
    });
  }
  return points;
};

